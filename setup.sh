# ---------------------------------------------------------------- 13. main ---
# The system half needs sudo and a reboot to show; the user half links,
# enables and reloads and is live at once. `install` is both, in order.
system_half() {
    install_packages
    enable_system_units
    install_system_files
    configure_boot
    configure_greeter
}

user_half() {
    # MIME defaults are re-applied on every run: any hand-installed app
    # (a browser most of all) can rewrite mimeapps.list and silently take
    # the PDF and image types with it
    set_default_apps
    configure_git
    link_configs
    install_templates
    enable_units
    install_shell_hooks
    configure_btop
    configure_micro
    apply_desktop_prefs

    niri validate
    log "ALL OK — niri config valid"
    reload_session
}

main() {
    case "${1:-install}" in
        install)
            system_half
            install_paru
            install_herdr
            user_half
            print_summary
            log "wallpaper: put an image at ~/Pictures/wallpaper.jpg (optional)"
            log "reboot: plymouth asks the passphrase, monogreet the login"
            ;;
        system)
            system_half
            print_summary
            log "reboot: plymouth asks the passphrase, monogreet the login"
            ;;
        link|configure)
            user_half
            log "configs are live symlinks — edits apply on save; commit in the repo when happy"
            ;;
        summary)
            print_summary
            ;;
        *)
            die "unknown command: $1 (usage: bash setup.sh [link|system|summary])"
            ;;
    esac
}

# Run only when executed, not when sourced (keeps functions testable).
if [ "${BASH_SOURCE[0]}" = "$0" ]; then
    main "$@"
fi
